fn main() {
    // Tauri scans every generated permission, including previous feature builds.
    // Recreate this ignored output from the current command list each time.
    let generated = std::path::Path::new("permissions/autogenerated");
    if generated.exists() {
        std::fs::remove_dir_all(generated)
            .expect("generated command permissions must be refreshed");
    }
    const COMMANDS: &[&str] = &[
        #[cfg(feature = "e2e")]
        "acp_acceptance_control",
        "desktop_terminal_admit",
        "desktop_terminal_release",
        "desktop_ai_user_commands",
        "desktop_ai_admit",
        "desktop_ai_release",
        "desktop_ai_backends",
        "desktop_repository_admit",
        "desktop_repository_release",
        "shell_info",
        "shell_ready",
        "desktop_clipboard_read",
        "desktop_clipboard_write",
        "desktop_external_open",
        "desktop_notify",
        "desktop_url_next",
        "desktop_url_ack",
        "desktop_url_enqueue",
        "lifecycle_reload",
        "lifecycle_quit",
        "lifecycle_result",
        "vault_recents",
        "vault_restore",
        "vault_remember_notes",
        "vault_select",
        "vault_open_recent",
        "vault_close",
        "vault_fs",
        "vault_watch_start",
        "vault_watch_stop",
        "vault_db_open",
        "vault_db_execute",
        "vault_db_close",
    ];
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(COMMANDS)),
    )
    .expect("Tauri build metadata and command permissions must be generated");
}
